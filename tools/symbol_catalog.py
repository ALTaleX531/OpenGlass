"""Validate and emit CodeView/PDB symbol-resolution catalogs."""

from __future__ import annotations

import re
import uuid
from pathlib import Path
from typing import Any, Sequence

from tools import projection_schema
from tools.projection_schema import ProjectionSchema, SchemaError, Symbol, SymbolBinding, Version, parse_uint, require_string


SCHEMA_VERSION = 2
SHA256_RE = re.compile(r"[0-9a-fA-F]{64}\Z")
GENERATED_NOTICE = "// Generated by tools/projection_codegen.py. Do not edit."


def _keys(value: dict[str, Any], allowed: set[str], context: str) -> None:
    unknown = set(value) - allowed
    missing = allowed - set(value)
    if unknown:
        raise SchemaError(f"{context}: unknown properties: {', '.join(sorted(unknown))}")
    if missing:
        raise SchemaError(f"{context}: missing properties: {', '.join(sorted(missing))}")


def _sha256(value: Any, context: str) -> str:
    result = require_string(value, context).lower()
    if not SHA256_RE.fullmatch(result):
        raise SchemaError(f"{context} must contain 64 hexadecimal characters")
    return result


def resolver_identity(value: Any, context: str) -> dict[str, str]:
    resolver = projection_schema.require_object(value, context)
    _keys(resolver, {"dbghelp"}, context)
    dbghelp = projection_schema.require_object(resolver["dbghelp"], f"{context}.dbghelp")
    _keys(dbghelp, {"version", "sha256"}, f"{context}.dbghelp")
    return {
        "version": require_string(dbghelp["version"], f"{context}.dbghelp.version"),
        "sha256": _sha256(dbghelp["sha256"], f"{context}.dbghelp.sha256"),
    }


def normalize_records(
    records: list[Any],
    schema: ProjectionSchema,
    source: Path,
    module: str,
    build: int,
) -> list[dict[str, Any]]:
    normalized: list[dict[str, Any]] = []
    for record_index, raw_record in enumerate(records):
        context = f"{source}.records[{record_index}]"
        record = projection_schema.require_object(raw_record, context)
        _keys(record, {"revision", "pdb", "symbols"}, context)
        revision = parse_uint(record["revision"], f"{context}.revision")
        version = Version(build, revision)
        if not projection_schema.in_range(version, schema):
            raise SchemaError(f"{context}: version is outside the {module} schema range")

        pdb = projection_schema.require_object(record["pdb"], f"{context}.pdb")
        _keys(pdb, {"name", "guid", "age", "sha256"}, f"{context}.pdb")
        pdb_name = require_string(pdb["name"], f"{context}.pdb.name")
        if Path(pdb_name).name != pdb_name or any(ord(character) < 0x20 or ord(character) > 0x7E for character in pdb_name):
            raise SchemaError(f"{context}.pdb.name must be a printable ASCII basename")
        try:
            pdb_guid = str(uuid.UUID(require_string(pdb["guid"], f"{context}.pdb.guid")))
        except ValueError as error:
            raise SchemaError(f"{context}.pdb.guid must be a GUID") from error
        pdb_age = parse_uint(pdb["age"], f"{context}.pdb.age", nonzero=True)
        pdb_hash = _sha256(pdb["sha256"], f"{context}.pdb.sha256")


        active: dict[str, tuple[int, Symbol, SymbolBinding]] = {}
        for symbol_index, symbol in enumerate(schema["symbols"]):
            selected = projection_schema.select_binding(version, symbol, "release")
            if selected is not None:
                active[symbol["id"]] = (symbol_index, symbol, selected[1])

        raw_symbols = projection_schema.require_object(record["symbols"], f"{context}.symbols")
        entries: list[dict[str, Any]] = []
        for symbol_id, raw_symbol_record in raw_symbols.items():
            symbol_context = f"{context}.symbols.{symbol_id}"
            if symbol_id not in active:
                raise SchemaError(f"{symbol_context}: Symbol is not active for this version")
            symbol_index, symbol, binding = active[symbol_id]
            symbol_record = projection_schema.require_object(raw_symbol_record, symbol_context)
            _keys(symbol_record, {"name", "rva"}, symbol_context)
            matched_name = require_string(symbol_record["name"], f"{symbol_context}.name")
            if matched_name not in binding["symbol_names"]:
                raise SchemaError(f"{symbol_context}.name is not in the selected binding")
            rva_text = require_string(symbol_record["rva"], f"{symbol_context}.rva")
            try:
                rva = int(rva_text, 0)
            except ValueError as error:
                raise SchemaError(f"{symbol_context}.rva must be a C-style integer string") from error
            parse_uint(rva, f"{symbol_context}.rva", nonzero=True)
            entries.append({"symbol_index": symbol_index, "rva": rva})
        entries.sort(key=lambda entry: entry["symbol_index"])

        missing_required = {
            symbol_id
            for symbol_id, (_, symbol, _) in active.items()
            if symbol["requirement"] == "required" and symbol_id not in raw_symbols
        }
        if missing_required:
            raise SchemaError(f"{context}.symbols omits Required IDs: {', '.join(sorted(missing_required))}")

        normalized.append({
            "module": module,
            "version": version,
            "configuration": "release",
            "pdb_name": pdb_name,
            "pdb_guid": pdb_guid,
            "pdb_age": pdb_age,
            "pdb_sha256": pdb_hash,
            "entries": entries,
        })
    return normalized


def validate_record_keys(records: Sequence[dict[str, Any]]) -> set[tuple[str, str, int]]:
    """Validate architecture-wide uniqueness and return the keys for collection reuse."""
    identities: set[tuple[str, str, int]] = set()
    for record in records:
        identity = (record["module"], record["pdb_guid"], record["pdb_age"])
        if identity in identities:
            raise SchemaError(f"duplicate module/PDB GUID/age across catalog sources: {identity}")
        identities.add(identity)
    return identities


def read_catalog_shard(path: Path) -> list[Any]:
    source = projection_schema.read_json(path)
    _keys(source, {"schema_version", "records"}, str(path))
    if source["schema_version"] != SCHEMA_VERSION:
        raise SchemaError(f"{path}: schema_version must be {SCHEMA_VERSION}")
    return projection_schema.require_list(source["records"], f"{path}.records")


def load_catalog_sources(index: Path, architecture: str, schemas: Sequence[ProjectionSchema]) -> dict[str, Any]:
    raw_index = projection_schema.read_json(index)
    _keys(raw_index, {"schema_version", "architecture", "resolver", "sources"}, str(index))
    if raw_index["schema_version"] != SCHEMA_VERSION:
        raise SchemaError(f"{index}: schema_version must be {SCHEMA_VERSION}")
    if raw_index["architecture"] != architecture:
        raise SchemaError(f"{index}: architecture must be {architecture}")
    resolver = resolver_identity(raw_index["resolver"], f"{index}.resolver")
    schemas_by_module = {schema["module"]: schema for schema in schemas}

    required_sources = {
        (module, build)
        for module, schema in schemas_by_module.items()
        for build in schema["known_builds"]
    }
    source_values = projection_schema.require_list(raw_index["sources"], f"{index}.sources")
    seen_keys: set[tuple[str, int]] = set()
    normalized: list[dict[str, Any]] = []
    for source_index, value in enumerate(source_values):
        relative = require_string(value, f"{index}.sources[{source_index}]")
        relative_path = Path(relative)
        if relative_path.is_absolute() or len(relative_path.parts) != 2 or relative_path.suffix.lower() != ".json":
            raise SchemaError(f"{index}.sources[{source_index}] must be module/BUILD.json")
        module = relative_path.parts[0]
        if module not in schemas_by_module or not relative_path.stem.isdigit():
            raise SchemaError(f"{index}.sources[{source_index}] must identify a known module and numeric build")
        build = int(relative_path.stem)
        key = (module, build)
        if key not in required_sources:
            raise SchemaError(f"{index}.sources[{source_index}]: module/build is not recognized by this architecture")
        path = (index.parent / relative_path).resolve()
        if key in seen_keys:
            raise SchemaError(f"{index}.sources[{source_index}]: duplicate source for {module} build {build}")
        seen_keys.add(key)

        source_records = read_catalog_shard(path)
        source_normalized = normalize_records(source_records, schemas_by_module[module], path, module, build)
        normalized.extend(source_normalized)
    if seen_keys != required_sources:
        missing = [f"{module}/{build}" for module, build in sorted(required_sources - seen_keys)]
        raise SchemaError(f"{index}: missing explicitly indexed sources: {', '.join(missing)}")

    validate_record_keys(normalized)

    normalized.sort(key=lambda item: (
        item["module"], item["version"].build, item["version"].revision,
        item["pdb_guid"], item["pdb_age"],
    ))
    return {
        "architecture": architecture,
        "resolver": resolver,
        "symbol_counts": {module: len(schema["symbols"]) for module, schema in schemas_by_module.items()},
        "records": normalized,
    }

def _guid_initializer(value: str) -> str:
    guid = uuid.UUID(value)
    data = guid.bytes_le
    data1 = int.from_bytes(data[0:4], "little")
    data2 = int.from_bytes(data[4:6], "little")
    data3 = int.from_bytes(data[6:8], "little")
    data4 = ", ".join(f"0x{byte:02X}" for byte in data[8:16])
    return f"{{0x{data1:08X}, 0x{data2:04X}, 0x{data3:04X}, {{{data4}}}}}"


def generate_files(catalog: dict[str, Any]) -> dict[str, str]:
    entries: list[int] = []
    record_rows: list[str] = []
    for record in catalog["records"]:
        dense_entries = [0] * catalog["symbol_counts"][record["module"]]
        for entry in record["entries"]:
            dense_entries[entry["symbol_index"]] = entry["rva"]
        first_entry = len(entries)
        entries.extend(dense_entries)
        module = "uDWM" if record["module"] == "udwm" else "DwmCore"
        record_rows.append(
            "\t\t{" +
            f"Projection::ModuleId::{module}, {_guid_initializer(record['pdb_guid'])}, {record['pdb_age']}u, " +
            f"std::span{{g_symbolCatalogEntries}}.subspan<{first_entry}, {len(dense_entries)}>()" +
            "},"
        )
    entry_rows = [
        f"\t\t0x{rva:X}u,"
        for rva in entries
    ]
    record_storage = record_rows or ["\t\t{},"]
    entry_storage = entry_rows or ["\t\t{},"]
    record_count = len(record_rows)
    header = "\n".join([
        GENERATED_NOTICE, "#pragma once", "", "namespace OpenGlass::Projection", "{",
        "\textern const SymbolCatalog g_builtInSymbolCatalog;", "}", "",
    ])
    implementation = "\n".join([
        GENERATED_NOTICE, "", "namespace OpenGlass::Projection::Generated", "{",
        "\tconstexpr UINT32 g_symbolCatalogEntries[] =", "\t{", *entry_storage, "\t};",
        "\tconstexpr Projection::SymbolCatalogRecord g_symbolCatalogRecords[] =", "\t{",
        *record_storage, "\t};", "}", "", "namespace OpenGlass::Projection", "{",
        "\tconst SymbolCatalog g_builtInSymbolCatalog", "\t{",
        f"\t\tstd::span{{Generated::g_symbolCatalogRecords}}.first<{record_count}>()", "\t};", "}", "",
    ])
    return {"SymbolCatalog.generated.hpp": header, "SymbolCatalog.generated.inc": implementation}
