"""Pure C++ emitters for validated projection schemas.

Every function in this module is deterministic and side-effect free. File-system
publication belongs to projection_codegen.py.
"""

from __future__ import annotations

from collections.abc import Iterable, Sequence

from tools.projection_schema import ProjectionSchema, Symbol, VersionSpec, normalize_target


GENERATED_NOTICE = "// Generated by tools/projection_codegen.py. Do not edit."


def array_lines(cpp_type: str, name: str, rows: list[str], qualifier: str = "constexpr") -> list[str]:
    if not rows:
        return [f"\t{qualifier} std::array<{cpp_type}, 0> {name}{{}};"]
    return [f"\t{qualifier} {cpp_type} {name}[] =", "\t{", *rows, "\t};"]


def zero_array(cpp_type: str, name: str, count: int) -> str:
    if not count:
        return f"\tstd::array<{cpp_type}, 0> {name}{{}};"
    return f"\t{cpp_type} {name}[{count}]{{}};"


def cpp_string_literal(value: str | bytes | bytearray) -> str:
    data = value.encode("utf-8") if isinstance(value, str) else value
    pieces: list[str] = []
    for byte in data:
        if byte == 0x5C:
            pieces.append("\\\\")
        elif byte == 0x22:
            pieces.append('\\"')
        elif 0x20 <= byte < 0x7F:
            pieces.append(chr(byte))
        else:
            # C++ octal escapes consume at most three digits, even before 0..9/A..F.
            pieces.append(f"\\{byte:03o}")
    return '"' + "".join(pieces) + '"'


class StringPool:
    def __init__(self) -> None:
        self.data = bytearray(b"\0")
        self.offsets: dict[str, int] = {"": 0}

    def add(self, value: str | None) -> int:
        if value is None:
            return 0
        if value in self.offsets:
            return self.offsets[value]
        encoded = value.encode("utf-8") + b"\0"
        offset = len(self.data)
        self.data.extend(encoded)
        self.offsets[value] = offset
        return offset

    def cpp_literal(self) -> str:
        return cpp_string_literal(self.data)


def condition_lines(condition: str | None, lines: Iterable[str]) -> list[str]:
    values = list(lines)
    if condition == "debug":
        return ["#ifdef _DEBUG", *values, "#endif"]
    return values


def generated_comment_lines(notes: str | list[str] | None, indent: str = "\t") -> list[str]:
    if notes is None:
        return []
    values = notes if isinstance(notes, list) else [notes]
    lines: list[str] = []
    for note in values:
        for line in note.splitlines():
            lines.append(f"{indent}//{f' {line}' if line else ''}")
    return lines


def generate_layout_header(schema: ProjectionSchema) -> str:
    namespace = schema["namespace"]
    tag = schema["tag"]
    module = schema["module"]
    lines = [
        GENERATED_NOTICE,
        "#pragma once",
        "",
        f"namespace {namespace}",
        "{",
        f"\tstruct {tag};",
        "\textern Projection::ModuleRegistry g_registry;",
        "}",
        "",
        f"namespace {namespace}::Generated",
        "{",
        (f"\textern LONG g_{module}SelectedOffsets[];" if schema["layouts"]
            else f"\textern std::array<LONG, 0> g_{module}SelectedOffsets;"),
        (f"\textern bool g_{module}LayoutSupported[];" if schema["layouts"]
            else f"\textern std::array<bool, 0> g_{module}LayoutSupported;"),
        "}",
        "",
        "namespace OpenGlass::Projection",
        "{",
        f"\ttemplate <> inline ModuleRegistry& RegistryFor<{namespace}::{tag}>() noexcept",
        "\t{",
        f"\t\treturn {namespace}::g_registry;",
        "\t}",
        "",
        f"\ttemplate <> struct LayoutState<{namespace}::{tag}>",
        "\t{",
        "\t\tstatic __forceinline LONG Offset(size_t index) noexcept",
        "\t\t{",
        f"\t\t\treturn {namespace}::Generated::g_{module}SelectedOffsets[index];",
        "\t\t}",
        "",
        "\t\tstatic __forceinline bool IsSupported(size_t index) noexcept",
        "\t\t{",
        f"\t\t\treturn {namespace}::Generated::g_{module}LayoutSupported[index];",
        "\t\t}",
        "\t};",
        "}",
        "",
        f"namespace {namespace}",
        "{",
        "",
    ]
    module_notes = generated_comment_lines(schema.get("notes"))
    if module_notes:
        lines.extend([*module_notes, ""])
    for index, layout in enumerate(schema["layouts"]):
        handle = "VtableSlotHandle" if layout["kind"] == "vtable_slot" else "FieldHandle"
        layout_notes = generated_comment_lines(layout.get("notes"))
        if layout_notes:
            lines.extend(layout_notes)
        lines.append(f"\tinline constexpr Projection::{handle}<{tag}, {index}, {layout['type']}> {layout['name']}{{}};")
        if layout_notes:
            lines.append("")
    lines.extend(["}", ""])
    return "\n".join(lines)


def symbol_cpp_type(symbol: Symbol) -> str:
    return symbol.get("type") or f"decltype({symbol['target']})"


def generate_symbol_header(schema: ProjectionSchema) -> str:
    namespace = schema["namespace"]
    tag = schema["tag"]
    lines = [GENERATED_NOTICE, "#pragma once", "", f"namespace {namespace}", "{", ""]
    for index, symbol in enumerate(schema["symbols"]):
        declaration = f"\tinline constexpr Projection::SymbolHandle<{tag}, {index}, {symbol_cpp_type(symbol)}> {symbol['name']}{{}};"
        lines.extend(condition_lines(symbol.get("condition"), [declaration]))
    lines.extend(["}", ""])
    return "\n".join(lines)


def requirement_cpp(value: str) -> str:
    return "Required" if value == "required" else "Optional"


def generate_registry_inc(schemas: Sequence[ProjectionSchema]) -> str:
    lines = [GENERATED_NOTICE, ""]
    for schema in schemas:
        module = schema["module"]
        namespace = schema["namespace"]
        pool = StringPool()
        symbol_name_offsets: list[int] = []
        versions: list[tuple[int, int]] = [(0, 0)]
        version_indices: dict[tuple[int, int], int] = {(0, 0): 0}

        def add_version(value: VersionSpec | None) -> int:
            if value is None:
                return 0
            key = (value["build"], value.get("revision", 0))
            if key not in version_indices:
                version_indices[key] = len(versions)
                versions.append(key)
            return version_indices[key]

        supported_minimum_index = add_version(schema.get("min_inclusive"))
        supported_maximum_index = add_version(schema.get("max_exclusive"))

        symbol_rows: list[str] = []
        binding_rows: list[str] = []
        binding_groups: dict[tuple[str, str], list[int]] = {}
        binding_symbols: list[int] = []
        binding_assertions: list[str] = []
        case_rows: list[str] = []
        layout_rows: list[str] = []
        for index, symbol in enumerate(schema["symbols"]):
            id_offset = pool.add(symbol["id"])
            requirement = f"Projection::Requirement::{requirement_cpp(symbol['requirement'])}"
            debug_only = "true" if symbol.get("condition") == "debug" else "false"
            for binding in symbol["bindings"]:
                first_name_index = len(symbol_name_offsets)
                symbol_name_offsets.extend(pool.add(candidate) for candidate in binding["symbol_names"])
                minimum_index = add_version(binding.get("min_inclusive"))
                maximum_index = add_version(binding.get("max_exclusive"))
                symbol_rows.append(
                    f"\t{{{index}, {id_offset}, {first_name_index}, {len(binding['symbol_names'])}, "
                    f"{minimum_index}, {maximum_index}, {requirement}, {debug_only}}},"
                )
            if symbol["kind"].startswith("projected_"):
                target = symbol["target"]
                binding_groups.setdefault((symbol["kind"], normalize_target(target)), []).append(index)
                if symbol["kind"] == "projected_function":
                    fallback = symbol.get("fallback") or f"Projection::ProjectedFailFast<{target}>"
                    binding_assertions.append(
                        f"\tstatic_assert(std::is_convertible_v<decltype({fallback}), Projection::projected_abi_t<{target}>>, "
                        f"{cpp_string_literal('fallback ABI mismatch: ' + symbol['id'])});"
                    )
                    compatibility = symbol.get("abi_compatibility")
                    if compatibility == "discard_return":
                        binding_assertions.append(
                            f"\tstatic_assert(Projection::is_discard_return_compatible_v<{symbol['type']}, "
                            f"Projection::projected_abi_t<{target}>>, {cpp_string_literal('discard-return ABI mismatch: ' + symbol['id'])});"
                        )
                    elif compatibility == "extra_trailing_argument":
                        binding_assertions.append(
                            f"\tstatic_assert(Projection::is_extra_trailing_argument_compatible_v<{symbol['type']}, "
                            f"Projection::projected_abi_t<{target}>>, {cpp_string_literal('trailing-argument ABI mismatch: ' + symbol['id'])});"
                        )

        for (kind, _), indices in binding_groups.items():
            symbol = schema["symbols"][indices[0]]
            target = symbol["target"]
            if kind == "projected_function":
                fallback = symbol.get("fallback") or f"Projection::ProjectedFailFast<{target}>"
                storage = f"Projection::ProjectedSlotStorage<{target}>()"
                fallback_value = f"Projection::ProjectedAddress({fallback})"
            else:
                storage = f"Projection::ProjectedVariableStorage<{target}>()"
                fallback_value = "nullptr"
            first_symbol = len(binding_symbols)
            binding_symbols.extend(indices)
            binding_rows.append(
                f"\t{{std::span{{g_{module}BindingSymbols}}.subspan<{first_symbol}, {len(indices)}>(), "
                f"{storage}, {fallback_value}}},"
            )

        first_case = 0
        for layout in schema["layouts"]:
            for case in layout["cases"]:
                boundary_index = add_version(case.get("until"))
                case_rows.append(f"\t{{{case['offset']}, {boundary_index}}},")
            layout_rows.append(f"\t{{{first_case}, {len(layout['cases'])}}},")
            first_case += len(layout["cases"])

        generated_namespace = f"{namespace}::Generated"
        lines.extend([
            f"namespace {generated_namespace}",
            "{",
            f"\tconstexpr char g_{module}StringPool[] = {pool.cpp_literal()};",
            f"\tconstexpr ULONG g_{module}KnownBuilds[] =",
            "\t{",
            *[f"\t\t{build}u," for build in schema["known_builds"]],
            "\t};",
            *array_lines("size_t", f"g_{module}SymbolNameOffsets", [f"\t\t{offset}," for offset in symbol_name_offsets]),
            f"\tconstexpr Projection::Version g_{module}Versions[] =",
            "\t{",
            *[f"\t\t{{{build}u, {revision}u}}," for build, revision in versions],
            "\t};",
            *array_lines("Projection::SymbolSpec", f"g_{module}SymbolSpecs", symbol_rows),
            zero_array("PVOID", f"g_{module}Candidates", len(schema["symbols"])),
            zero_array("PVOID", f"g_{module}Resolved", len(schema["symbols"])),
            zero_array("Projection::ResolutionState", f"g_{module}ResolutionStates", len(schema["symbols"])),
            *binding_assertions,
            f"\tconstexpr std::array<size_t, {len(binding_symbols)}> g_{module}BindingSymbols{{{', '.join(map(str, binding_symbols))}}};",
            *array_lines("Projection::BindingSpec", f"g_{module}Bindings", binding_rows, "const"),
            *array_lines("Projection::LayoutCase", f"g_{module}LayoutCases", case_rows),
            *array_lines("Projection::LayoutSpec", f"g_{module}LayoutSpecs", layout_rows),
            (f"\tLONG g_{module}SelectedOffsets[std::size(g_{module}LayoutSpecs)]{{}};" if layout_rows
                else zero_array("LONG", f"g_{module}SelectedOffsets", 0)),
            (f"\tbool g_{module}LayoutSupported[std::size(g_{module}LayoutSpecs)]{{}};" if layout_rows
                else zero_array("bool", f"g_{module}LayoutSupported", 0)),
            "}",
            "",
            f"namespace {namespace}",
            "{",
            f"\tconstinit Projection::ModuleRegistry g_registry{{",
            f"\t\t\"{'uDWM.dll' if module == 'udwm' else 'dwmcore.dll'}\",",
            f"\t\tGenerated::g_{module}StringPool, std::span{{Generated::g_{module}SymbolNameOffsets}}, std::span{{Generated::g_{module}Versions}},",
            f"\t\tstd::span{{Generated::g_{module}KnownBuilds}},",
            f"\t\tstd::span{{Generated::g_{module}SymbolSpecs}},",
            f"\t\tstd::span{{Generated::g_{module}Candidates}}, std::span{{Generated::g_{module}Resolved}},",
            f"\t\tstd::span{{Generated::g_{module}ResolutionStates}}, std::span{{Generated::g_{module}Bindings}},",
            f"\t\tstd::span{{Generated::g_{module}LayoutSpecs}}, std::span{{Generated::g_{module}LayoutCases}},",
            f"\t\tstd::span{{Generated::g_{module}SelectedOffsets}}, std::span{{Generated::g_{module}LayoutSupported}},",
            f"\t\tProjection::VersionRange{{Generated::g_{module}Versions[{supported_minimum_index}], Generated::g_{module}Versions[{supported_maximum_index}]}}}};",
            "}",
            "",
        ])
    return "\n".join(lines)


def generate_files(schemas: Sequence[ProjectionSchema]) -> dict[str, str]:
    """Generate the complete, fixed output set for one architecture."""
    by_module = {schema["module"]: schema for schema in schemas}
    return {
        "udwm.Layouts.generated.hpp": generate_layout_header(by_module["udwm"]),
        "udwm.Symbols.generated.hpp": generate_symbol_header(by_module["udwm"]),
        "dwmcore.Layouts.generated.hpp": generate_layout_header(by_module["dwmcore"]),
        "dwmcore.Symbols.generated.hpp": generate_symbol_header(by_module["dwmcore"]),
        "ProjectionRegistry.generated.inc": generate_registry_inc(schemas),
    }
